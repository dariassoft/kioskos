import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import { VitePWA } from 'vite-plugin-pwa'
import path from 'path'
import fs from 'fs'

let buildOutDir = 'dist'
try {
  const preferredOutDir = path.resolve(__dirname, 'dist')
  const preferredAssetsDir = path.resolve(preferredOutDir, 'assets')

  fs.accessSync(preferredOutDir, fs.constants.W_OK)
  if (fs.existsSync(preferredAssetsDir)) {
    fs.accessSync(preferredAssetsDir, fs.constants.W_OK)
  }
} catch {
  buildOutDir = 'dist-local'
}

export default defineConfig({
  plugins: [
    react(),
    VitePWA({
      registerType: 'autoUpdate',
      devOptions: {
        enabled: true
      },
      manifest: {
        name: 'Kioskos & Despenzas POS',
        short_name: 'KioskosPOS',
        description: 'Punto de Venta y Gestión de Inventario',
        theme_color: '#0f172a',
        icons: [
          {
            src: 'pwa-192x192.png',
            sizes: '192x192',
            type: 'image/png'
          },
          {
            src: 'pwa-512x512.png',
            sizes: '512x512',
            type: 'image/png'
          }
        ]
      }
    })
  ],
  resolve: {
    alias: {
      '@': path.resolve(__dirname, './src'),
      '@components': path.resolve(__dirname, './src/components'),
      '@pages': path.resolve(__dirname, './src/pages'),
      '@layouts': path.resolve(__dirname, './src/layouts'),
      '@store': path.resolve(__dirname, './src/store'),
      '@hooks': path.resolve(__dirname, './src/hooks'),
      '@api': path.resolve(__dirname, './src/api'),
      '@lib': path.resolve(__dirname, './src/lib'),
    },
  },
  server: {
    port: 5173,
    host: true,
    proxy: {
      '/api': {
        target: 'http://localhost:3000',
        changeOrigin: true,
      },
    },
  },
  build: {
    outDir: buildOutDir,
  },
})
